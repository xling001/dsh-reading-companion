/**
 * 章号锚：`` `第12章` `` / `` `第12-15章` `` —— **全仓唯一的一份口径**。
 *
 * ## 为什么单独成一个文件
 *
 * 2026-10-02 三方评审 P3-2 实测：这条判据在仓库里存在**两套口径**，而且互不咬合 ——
 *   · 切分（`background.js` 的 `splitParagraph`）：反引号**可选**；
 *   · 判读（`minChapterIn` / `maxChapterIn`）：反引号**必需**。
 *
 * 于是"漏打反引号"的条目会**切开却每片都判成没章号**（`earliest === 0` ⇒ 当"通用描述"
 * 留下）—— 切开等于白切，后文那半句照旧进注入。同一句话只差两个反引号，结果一个挡住、
 * 一个放行（主评审与 A 各自复跑一致）。
 *
 * 读者 2026-10-02 拍板：**判读也接受无反引号**。理由是"切了却不判"比"不切"更糟 ——
 * 前者看起来做了防护、实际没有，后者至少形状一致、一眼能看出没防。所以两份口径统一到
 * **宽松那一版**：`第3章` 与 `` `第3章` `` 等价。
 *
 * ## 为什么是函数而不是常量
 *
 * 这些正则都带 `g`，而带 `g` 的正则有 `lastIndex` 状态：**共用同一个对象会互相打断**
 * （`background.js` 里那条老注释记的就是这个坑）。所以每次要扫就取一个新实例。
 *
 * @returns {RegExp} 新的宽松章号锚正则（带 `g`，捕获组 1 = 起始章号，组 2 = 区间终点章号）
 */
export function anchorRegex() {
  return /`?第\s*(\d+)(?:\s*[-–~]\s*(\d+))?\s*章`?/g
}
