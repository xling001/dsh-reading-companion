/**
 * 记忆补齐 —— 一次调用，补「缺失的全部前文」这一整段。
 *
 * ## 与早期设计的区别
 *
 * 早期是**每章一条梗概**：翻到第 5 章就为第 5 章起一个子代理，第 6 章再起一个。
 * 一本 300 章的书意味着 300 次模型调用，而每次只处理一章——既贵，又把
 * "理解"切成了互不相干的碎片。
 *
 * 现在是**一次调用处理一整段缺口**：把 `[缺口起点 .. 前文末章]` 抽样后一起交给
 * 一个子代理，让它产出**结构化的背景认识** —— 八节：`文本类型` / `人物状态` /
 * `人物关系` / `人物` / `世界观` / `文风（只写一次）` / `通用概念` / `时间与分线`，
 * 合并进 `background.md`，然后水位线推到位。章节数不再等于调用次数。
 *
 * ⚠️ 2026-10-04 更正：这里从前写的是"六节"、而且列着**已并入别处**的「前文脉络」
 *    （3.0 并进「时间与分线」）—— 一处**失效引用**，评审发现。以 `sections.js` 的
 *    注册表为准（那份是唯一来源）；「冷档案」是**代码**搬运的归档区，不由子代理写。
 *
 * ## 子代理是谁
 *
 * 它不是"陪读 AI"，而是**读者自己的整理笔记的那一面**。这个身份很重要：
 * 陪读 AI 有"不许说后续"的对话约束，而整理笔记需要的是"如实记录我从已读部分
 * 看出了什么"。两种任务用同一个 persona 只会互相打架。
 *
 * ## 机制部分不在这里
 *
 * 父 Agent 查找、超时 race、联网工具面的降级都在 `subagent-run.js`——压缩
 * （`compact.js`）要的是同一套东西，只写一遍。
 *
 * ## 三条 2026-10-03 的约定（改这个文件之前先看）
 *
 * 1. **一批的输出有预算**（{@link MEMORY_ENTRY_BUDGET} / {@link MEMORY_CHAR_BUDGET}）：
 *    写在提示词的固定块里（跨批逐字相同 ⇒ 不破坏稳定前缀），是**事前**约束；
 *    它**不能**取代事后那条"砍半章数重试"（`index.js`）—— 见下面 `fill()` 的说明。
 * 2. **「文本类型」只判两件事**（读者 2026-10-03 收窄）：**属于什么类型 + 主视角是谁**，
 *    **40 字以内**，其余**一律不判**（人物关系 / 感情线 / cp / 谁是女主 / 故事走向），
 *    剧情用省略号带过。它只写一次、之后每批都注入 ⇒ **判错会被永久带下去**，
 *    所以判据必须是"这一批里**读得出来**的事"，而不是"读者想知道的事"。
 *    ⚠️ 反面教材（实测）：老版本格式块里问"**有没有 cp？**"，模型照问作答，
 *    在一本女主很晚才出现的书上写下"有 cp（孟奇 ↔ 江芷微等同伴）"。
 * 3. **「文本类型」只写一次、之后每批都注入**（读者 2026-10-03 定回来）。
 *    ⚠️ 它**不是**可重判的：误判风险由第 2 条（收窄判据）来避免，而不是靠纠错口。
 *    读者原话："为了文本类型对后续条目变形方向指导的稳定性，我认为这一块还是改回
 *    之前的只写一次持续注入比较好，不需要重写，误判的风险我们通过模糊化的简介来避免就好。"
 *    **"稳定性"是关键词**：它是**每批都注入的写法指南针**，一改，后面所有批次的写法方向
 *    跟着变；而"改"这个动作本身（哪怕改对了）也会让已经写下的条目与新方向不一致。
 *    ⇒ **宁可一开始写得模糊，也不要中途转向。**
 * 4. **"各节该往哪个方向用力"住在提示词的固定块里（第 20 条），不在文件里**（2026-10-03 读者拍板）。
 *    它原来的家是「文本类型」，但那个节是 `family: 'full'` —— **每个聊天轮次都整条注入**，
 *    而"用力方向"的消费者只有**补齐子代理** ⇒ 放在文件里等于让**聊天为一份用不上的指令
 *    永久付费**，还叠上"只写一次 ⇒ 错一次永久定向"的放大器。
 *    搬进固定块之后：聊天零成本、**每批都重新说一遍**（能在后文证据面前自然演化）、
 *    而且它**就在原则旁边** ⇒ "指导不得凌驾于原则"由**位置**保证，而不是靠一句叮嘱。
 */

